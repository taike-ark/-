/// 通过 MAC 地址查厂商。
pub fn lookup(mac: &str) -> Option<&'static str> {
    let norm = normalize_mac(mac)?;
    let prefix = &norm[0..8];
    // 二分查找
    let mut lo = 0usize;
    let mut hi = OUI.len();
    while lo < hi {
        let mid = (lo + hi) / 2;
        match OUI[mid].0.cmp(prefix) {
            std::cmp::Ordering::Less => lo = mid + 1,
            std::cmp::Ordering::Greater => hi = mid,
            std::cmp::Ordering::Equal => return Some(OUI[mid].1),
        }
    }
    None
}

/// 规范化为 "AA:BB:CC:DD:EE:FF"
pub fn normalize_mac(mac: &str) -> Option<String> {
    let hex: String = mac
        .chars()
        .filter(|c| c.is_ascii_hexdigit())
        .collect::<String>()
        .to_ascii_uppercase();
    if hex.len() != 12 {
        return None;
    }
    let mut out = String::with_capacity(17);
    for i in 0..6 {
        if i > 0 {
            out.push(':');
        }
        out.push_str(&hex[i * 2..i * 2 + 2]);
    }
    // 过滤全 0 / 广播 / 组播
    if out == "00:00:00:00:00:00" || out.starts_with("FF:FF:FF") {
        return None;
    }
    Some(out)
}

/// 判断是否为本地管理地址（虚拟网卡常见）
pub fn is_locally_administered(mac: &str) -> bool {
    if let Some(n) = normalize_mac(mac) {
        let first = u8::from_str_radix(&n[0..2], 16).unwrap_or(0);
        return first & 0x02 != 0;
    }
    false
}
